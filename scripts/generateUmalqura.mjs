// Generates lib/umalquraData.ts: the Umm al-Qura calendar's month lengths and
// the day 1 Muharram 1300 AH falls on, read from Node's built-in ICU
// (Intl 'islamic-umalqura'). Run with `node scripts/generateUmalqura.mjs` if
// the range ever needs extending; scripts/verifyUmalqura.ts then checks the
// result against ICU day by day.
import { writeFileSync } from 'node:fs';

const FIRST_YEAR = 1300;
const LAST_YEAR = 1500; // inclusive
const fmt = new Intl.DateTimeFormat('en-u-ca-islamic-umalqura-nu-latn', {
  day: 'numeric', month: 'numeric', year: 'numeric', timeZone: 'UTC',
});
const hijriOf = (epochDay) => {
  const p = Object.fromEntries(fmt.formatToParts(new Date(epochDay * 86400000)).map((x) => [x.type, x.value]));
  return { year: +p.year, month: +p.month, day: +p.day };
};

// Walk day by day from a start comfortably before 1300 AH (1882 CE).
let day = Math.floor(Date.UTC(1882, 0, 1) / 86400000);
while (!(hijriOf(day).year === FIRST_YEAR && hijriOf(day).month === 1 && hijriOf(day).day === 1)) day++;
const firstEpochDay = day;

let lengths = '';
let current = { year: FIRST_YEAR, month: 1 };
let count = 0;
while (current.year <= LAST_YEAR) {
  const h = hijriOf(day);
  if (h.year !== current.year || h.month !== current.month) {
    if (count !== 29 && count !== 30) throw new Error(`Bad month length ${count} at ${current.year}-${current.month}`);
    lengths += count === 30 ? '1' : '0';
    current = { year: h.year, month: h.month };
    count = 0;
    if (h.day !== 1) throw new Error('Month did not start on day 1');
  }
  count++;
  day++;
}
const months = (LAST_YEAR - FIRST_YEAR + 1) * 12;
if (lengths.length !== months) throw new Error(`Expected ${months} months, got ${lengths.length}`);

writeFileSync(
  new URL('../lib/umalquraData.ts', import.meta.url),
  `// Generated by scripts/generateUmalqura.mjs - do not edit by hand.
// Umm al-Qura calendar, ${FIRST_YEAR}-${LAST_YEAR} AH (${new Date(firstEpochDay * 86400000).getUTCFullYear()}-${new Date(day * 86400000).getUTCFullYear()} CE).

/** Days since 1970-01-01 (UTC) of 1 Muharram ${FIRST_YEAR} AH. */
export const FIRST_EPOCH_DAY = ${firstEpochDay};

export const FIRST_YEAR = ${FIRST_YEAR};

/** One character per month from Muharram ${FIRST_YEAR}: '1' = 30 days, '0' = 29 days. */
export const MONTH_LENGTHS = '${lengths}';
`
);
console.log('wrote', months, 'months; first epoch day', firstEpochDay, new Date(firstEpochDay * 86400000).toISOString().slice(0, 10));
